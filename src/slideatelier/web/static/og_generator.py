"""Standalone, stdlib-only generator for /static/og.png.

The OG image is a 1200x630 PNG used by Twitter / Facebook / LinkedIn link
previews. Real launch art belongs to a designer; for the launch we ship a
solid brand-amber background with a simple wordmark + tagline rendered
pixel-by-pixel from a tiny built-in 8x8 bitmap font (so we don't take a
Pillow dependency for one placeholder asset).

Run:  python og_generator.py
Writes: og.png  in the same directory.
"""
from __future__ import annotations


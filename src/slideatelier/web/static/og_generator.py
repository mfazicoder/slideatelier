def render_text(pixels: list[list[tuple[int, int, int]]], text: str, x: int, y: int, scale: int, color: tuple[int, int, int]) -> None:
    """Render `text` at (x, y) as `scale`× scaled-up pixels of the bitmap font."""
    cx = x
    for ch in text:
        glyph = FONT.get(ch, FONT[" "])
        for row in range(8):
            bits = glyph[row]
            for col in range(8):
                if bits & (0x80 >> col):
                    px = cx + col * scale
                    py = y + row * scale
                    for dy in range(scale):
                        for dx in range(scale):
                            xx, yy = px + dx, py + dy
                            if 0 <= xx < W and 0 <= yy < H:
                                pixels[yy][xx] = color
        cx += 8 * scale  # 1-cell advance, fixed-width font


def build_pixels() -> list[list[tuple[int, int, int]]]:
    pixels = [[BG for _ in range(W)] for _ in range(H)]

    # Accent stripe at top — 12px tall amber-300 band.
    for y in range(0, 12):
        for x in range(W):
            pixels[y][x] = ACCENT

    # Wordmark: "slideAtelier"  (scale=10 → 80px tall caps).
    render_text(pixels, "slideAtelier", x=140, y=210, scale=10, color=FG)

    # Tagline: "AI presentations · native PowerPoint · public web URL"
    render_text(
        pixels,
        "AI decks  native PowerPoint  public web URL",
        x=140,
        y=370,
        scale=4,
        color=FG,
    )

    # Bottom caption line.
    render_text(
        pixels,
        "slideatelier.com",
        x=140,
        y=540,
        scale=3,
        color=ACCENT,
    )
    return pixels


def write_png(pixels: list[list[tuple[int, int, int]]], path: Path) -> None:
    raw = bytearray()
    for row in pixels:
        raw.append(0)  # filter byte = None
        for r, g, b in row:
            raw.extend((r, g, b))
    compressed = zlib.compress(bytes(raw), 9)

    def chunk(tag: bytes, data: bytes) -> bytes:
        crc = zlib.crc32(tag + data) & 0xFFFFFFFF
        return struct.pack(">I", len(data)) + tag + data + struct.pack(">I", crc)

    sig = b"\x89PNG\r\n\x1a\n"
    ihdr = struct.pack(">IIBBBBB", W, H, 8, 2, 0, 0, 0)  # 8-bit RGB
    blob = sig + chunk(b"IHDR", ihdr) + chunk(b"IDAT", compressed) + chunk(b"IEND", b"")
    path.write_bytes(blob)


if __name__ == "__main__":
    out = Path(__file__).parent / "og.png"
    write_png(build_pixels(), out)
    print(f"wrote {out} ({out.stat().st_size:,} bytes)")
